def university():
    r = random.Random(303)
    faculties = {"Business": 3200, "Engineering": 2600, "Health Sciences": 2900, "Arts & Humanities": 1700, "Computing": 2100, "Law": 1100}
    years = ["2021/22", "2022/23", "2023/24", "2024/25", "2025/26"]
    trend = {"Business": [1, 1.05, 1.08, 1.02, 0.97], "Engineering": [1, 1.02, 1.04, 1.07, 1.1], "Health Sciences": [1, 1.06, 1.1, 1.15, 1.18],
             "Arts & Humanities": [1, 0.96, 0.91, 0.86, 0.8], "Computing": [1, 1.12, 1.25, 1.33, 1.41], "Law": [1, 1.0, 1.02, 1.01, 1.03]}
    # Year labels like 2021/22 are not recognised as periods, so the enrolment tab uses year columns "2022" etc.
    ycols = ["2022", "2023", "2024", "2025", "2026"]
    enrol = [(f, [int(base * m * r.uniform(0.99, 1.01)) for m in trend[f]]) for f, base in faculties.items()]

    programmes = {"Business": ["BA Accounting", "BSc Management", "MBA"], "Engineering": ["BEng Mechanical", "BEng Civil", "MEng Electrical"],
                  "Health Sciences": ["BSc Nursing", "BSc Physiotherapy", "MSc Public Health"], "Arts & Humanities": ["BA History", "BA English", "BA Fine Art"],
                  "Computing": ["BSc Computer Science", "BSc Data Science", "MSc AI"], "Law": ["LLB Law", "LLM International Law"]}
    students = []
    for i in range(1, 901):
        fac = r.choices(list(faculties), weights=list(faculties.values()))[0]
        prog = r.choice(programmes[fac])
        fee = "International" if r.random() < (0.38 if fac in ("Business", "Computing") else 0.18) else "Home"
        fac_att = {"Business": 84, "Engineering": 88, "Health Sciences": 92, "Arts & Humanities": 78, "Computing": 83, "Law": 87}[fac]
        attendance = max(35, min(100, round(r.gauss(fac_att + (3 if fee == "International" else 0), 9))))
        avg = max(28, min(92, round(r.gauss(61, 10) + (attendance - 85) * 0.35, 1)))
        withdraw_p = 0.03 + (0.16 if attendance < 70 else 0) + (0.05 if fac == "Arts & Humanities" else 0)
        cont = "Withdrawn" if r.random() < withdraw_p else "Continued"
        students.append([f"S{240000 + i}", fac, prog, r.choice([1, 2, 3]), fee, attendance, avg, cont])
    stu_cols = ["Student ID", "Faculty", "Programme", "Year of study", "Fee status", "Attendance %", "Module average", "Continuation"]

    themes = ["Teaching", "Assessment and feedback", "Academic support", "Organisation", "Learning resources", "Student voice"]
    nss = [[f, th, round(min(97, max(55, r.gauss(79, 6))), 1)] for f in faculties for th in themes]
    nss_cols = ["Faculty", "Theme", "Agree score"]

    funders = ["UKRI", "Wellcome Trust", "Industry", "EU Horizon", "Charities"]
    research = []
    for f in faculties:
        for y in ycols:
            for fu in funders:
                if r.random() < 0.6:
                    research.append([f, fu, y, gbp(r.uniform(40000, 900000) * (1.8 if f in ("Engineering", "Health Sciences") else 0.7))])
    res_cols = ["Faculty", "Funder", "Year", "Income"]

    wb = Workbook()
    readme_tab(wb, "Ashford University: planning data", [
        "Enrolment: headcount by faculty over five academic years (years across the top; 2026 means 2025/26).",
        "Students: one row per student with attendance, module average and whether they continued.",
        "Student survey: agreement scores by faculty and theme (averaged, not added up).",
        "Research income: by faculty, funder and year.",
    ])
    statement(wb, "Enrolment", "Ashford University: enrolment by faculty", "Headcount at 1 December; 2026 = academic year 2025/26.", enrol, ycols, fmt="#,##0")
    ws = wb.create_sheet("Students")
    write_table(ws, stu_cols, students, widths={"Programme": 24})
    ws = wb.create_sheet("Student survey")
    write_table(ws, nss_cols, nss, widths={"Theme": 26})
    ws = wb.create_sheet("Research income")
    write_table(ws, res_cols, research, formats={"Income": GBP})
    wb.save(OUT / "university-ashford.xlsx")

    st = frame(stu_cols, students)
    low = st[st["Attendance %"] < 70]
    return {
        "students_rows": len(st),
        "average_attendance_by_faculty": {k: round(v, 2) for k, v in st.groupby("Faculty")["Attendance %"].mean().items()},
        "withdrawal_rate": round((st["Continuation"] == "Withdrawn").mean() * 100, 1),
        "withdrawal_rate_low_attendance": round((low["Continuation"] == "Withdrawn").mean() * 100, 1),
        "enrolment_2026": {f: v[-1] for f, v in enrol},
        "average_agree_by_faculty": {k: round(v, 2) for k, v in frame(nss_cols, nss).groupby("Faculty")["Agree score"].mean().items()},
    }


