# 1. Law firm: time, matters, management accounts, aged debt
# ---------------------------------------------------------------------------------------------
def law_firm():
    r = random.Random(101)
    grades = {"Partner": (395, 4.6), "Senior Associate": (310, 5.6), "Associate": (245, 6.0), "Trainee": (160, 5.4), "Paralegal": (125, 5.8)}
    people = [
        ("Eleanor Hartwell", "Partner"), ("Marcus Lane", "Partner"), ("Priya Raman", "Partner"),
        ("Tom Ashby", "Senior Associate"), ("Grace Okafor", "Senior Associate"), ("Daniel Moretti", "Senior Associate"),
        ("Hannah Cole", "Associate"), ("Yusuf Malik", "Associate"), ("Sophie Wren", "Associate"), ("Liam Doyle", "Associate"),
        ("Aisha Begum", "Trainee"), ("Oliver Grant", "Trainee"), ("Chloe Fenn", "Paralegal"), ("Ravi Shah", "Paralegal"),
    ]
    areas = ["Corporate", "Litigation", "Employment", "Real Estate", "Private Client"]
    clients = ["Brightwater Foods", "Calder Logistics", "Fenwick Estates", "Harbour Dental Group", "Kestrel Software",
               "Linden Care Homes", "Marlow Engineering", "Northgate Retail", "Oakridge Academy Trust", "Pemberton Family",
               "Quayside Hotels", "Redfern Pharma", "Silverline Haulage", "Thornbury Farms", "Vale Credit Union"]
    partners = {"Corporate": "Eleanor Hartwell", "Litigation": "Marcus Lane", "Employment": "Priya Raman",
                "Real Estate": "Eleanor Hartwell", "Private Client": "Priya Raman"}
    fee_types = {"Corporate": "Hourly", "Litigation": "Hourly", "Employment": "Capped", "Real Estate": "Fixed", "Private Client": "Fixed"}

    matters = []
    for i in range(1, 37):
        area = areas[(i - 1) % 5] if i <= 30 else r.choice(areas)
        client = clients[(i * 7) % len(clients)]
        opened = date(2026, 1, 1) + timedelta(days=r.randint(0, 200))
        matters.append({"Matter ID": f"HL-{2600 + i}", "Client": client, "Practice area": area, "Partner": partners[area],
                        "Opened": opened, "Fee type": fee_types[area]})

    months = month_starts(date(2026, 4, 1), 6)
    time_rows = []
    for name, grade in people:
        rate, daily = grades[grade]
        home = r.sample(areas, 2)
        for m in months:
            for _ in range(r.randint(55, 63)):  # about three entries a working day
                matter = r.choice([x for x in matters if x["Practice area"] in home] or matters)
                hours = round(max(0.5, r.gauss(daily / 3, 0.6)) * 2) / 2
                activity = r.choices(ACTIVITIES, weights=[30, 18, 10, 16, 12, 8 if grade != "Partner" else 14, 6 if grade != "Partner" else 12])[0]
                billable = activity not in NON_BILLABLE
                time_rows.append([rand_day(r, m), name, matter["Practice area"], grade, matter["Matter ID"], matter["Client"],
                                  activity, hours, rate, round(hours * rate, 2) if billable else 0.0])
    # The clean samples have no exact duplicates (two identical entries on the same day); the
    # complex/messy pack is where duplicates are planted.
    time_rows = [list(t) for t in dict.fromkeys(tuple(row) for row in time_rows)]
    time_rows.sort(key=lambda x: (x[0], x[1]))
    # Workbench charts the first number column by the category with the fewest values, so Practice area
    # comes before Grade (both have five) and Hours is the first number.
    time_cols = ["Date", "Fee earner", "Practice area", "Grade", "Matter ID", "Client", "Activity", "Hours", "Rate", "Value"]
    t = frame(time_cols, time_rows)

    # Matters: billing outcome per matter from the recorded time
    by_matter = t.groupby("Matter ID")["Value"].sum()
    mat_rows = []
    for m in matters:
        wip = gbp(by_matter.get(m["Matter ID"], 0.0))
        real = {"Corporate": 0.93, "Litigation": 0.86, "Employment": 0.81, "Real Estate": 0.77, "Private Client": 0.9}[m["Practice area"]]
        billed = gbp(wip * real * r.uniform(0.92, 1.02))
        collected = gbp(billed * r.uniform(0.62, 0.98))
        mat_rows.append([m["Matter ID"], m["Client"], m["Practice area"], m["Partner"], m["Opened"], m["Fee type"],
                         wip, billed, collected, gbp(billed - collected)])
    mat_cols = ["Matter ID", "Client", "Practice area", "Partner", "Opened", "Fee type", "Time value", "Billed", "Collected", "Unpaid"]
    mt = frame(mat_cols, mat_rows)

    fee = [gbp(t[pd.to_datetime(t["Date"]).dt.month == mo.month]["Value"].sum() * 0.87) for mo in months]
    disb = [gbp(x * 0.04) for x in fee]
    salaries = [gbp(r.uniform(128000, 132000)) for _ in months]
    rent = [32500.0] * 6
    pii = [9800.0] * 6
    it = [gbp(r.uniform(11000, 14500)) for _ in months]
    mkt = [gbp(r.uniform(4000, 9000)) for _ in months]
    total_income = [gbp(a + b) for a, b in zip(fee, disb)]
    total_costs = [gbp(sum(x)) for x in zip(salaries, rent, pii, it, mkt)]
    net = [gbp(a - b) for a, b in zip(total_income, total_costs)]
    pl = [("Fee income", fee), ("Disbursements recovered", disb), ("Total income", total_income),
          ("Salaries", salaries), ("Rent and rates", rent), ("Professional indemnity", pii),
          ("IT and case management", it), ("Marketing", mkt), ("Total costs", total_costs), ("Net profit", net)]

    # Aged debt splits each client's unpaid bills (from Matters) by age, so the two tabs agree.
    unpaid_by_client = mt.groupby("Client")["Unpaid"].sum()
    debt_rows = []
    for c in clients:
        owed = gbp(unpaid_by_client.get(c, 0.0))
        w = [0.05, 0.1, 0.15, 0.7] if c in ("Northgate Retail", "Silverline Haulage") else [r.uniform(0.3, 0.6), r.uniform(0.15, 0.3), r.uniform(0.05, 0.15), r.uniform(0, 0.1)]
        b = [gbp(owed * x / sum(w)) for x in w[:3]]
        b.append(gbp(owed - sum(b)))
        debt_rows.append([c, owed, *b])
    debt_rows.sort(key=lambda x: -x[1])
    debt_cols = ["Client", "Owed", "0-30 days", "31-60 days", "61-90 days", "Over 90 days"]

    wb = Workbook()
    readme_tab(wb, "Hartwell & Lane LLP: practice data, April to September 2026", [
        "Time entries: every recorded hour, by fee earner, grade, practice area and matter.",
        "Matters: time value, billed, collected and unpaid per matter.",
        "Management accounts: a monthly P&L with a title block above the table, as practice systems export it.",
        "Aged debt: what each client owes, by age.",
    ])
    ws = wb.create_sheet("Time entries")
    write_table(ws, time_cols, time_rows, formats={"Rate": GBP, "Value": GBP2}, widths={"Fee earner": 20, "Client": 24})
    ws = wb.create_sheet("Matters")
    write_table(ws, mat_cols, mat_rows, formats={k: GBP for k in ["Time value", "Billed", "Collected", "Unpaid"]}, widths={"Client": 24, "Partner": 20})
    statement(wb, "Management accounts", "Hartwell & Lane LLP: management accounts", "Monthly, £. Unaudited.", pl, MONTHS_FY)
    ws = wb.create_sheet("Aged debt")
    write_table(ws, debt_cols, debt_rows, formats={k: GBP for k in debt_cols[1:]}, widths={"Client": 24})
    wb.save(OUT / "law-firm-hartwell-lane.xlsx")

    bill = t[~t["Activity"].isin(NON_BILLABLE)]
    expected = {
        "time_entries_rows": len(t),
        "value_by_practice_area": {k: gbp(v) for k, v in t.groupby("Practice area")["Value"].sum().items()},
        "billable_hours_share": round(bill["Hours"].sum() / t["Hours"].sum() * 100, 1),
        "realisation_by_practice_area": {k: round(g["Billed"].sum() / g["Time value"].sum() * 100, 1) for k, g in mt.groupby("Practice area")},
        "unpaid_total": gbp(mt["Unpaid"].sum()),
        "over_90_days_total": gbp(sum(row[5] for row in debt_rows)),
        "net_profit_by_month": dict(zip(MONTHS_FY, net)),
    }
    return expected


