"""Build the showcase sample pack in public/sample-data/.

Every company, person and number is fictional and generated from a fixed seed, so the files and
the expected results in public/sample-data/expected.json are the same on every run. The expected
results are computed here with pandas and checked against the Workbench code in
src/lib/showcase.test.js and against the server in backend/tests/test_showcase_pack.py, so the
demo script never promises a number the product does not show.

Run from the repo root:  python scripts/build_showcase.py
"""
from __future__ import annotations

import json
import random
from datetime import date, timedelta
from pathlib import Path

import pandas as pd
from openpyxl import Workbook
from openpyxl.styles import Alignment, Font, PatternFill
from openpyxl.utils import get_column_letter

OUT = Path(__file__).resolve().parent.parent / "public" / "sample-data"
NAVY = "0F1B2D"
HEAD_FILL = PatternFill("solid", fgColor=NAVY)
HEAD_FONT = Font(bold=True, color="FFFFFF")
TITLE_FONT = Font(bold=True, size=14, color=NAVY)
NOTE_FONT = Font(italic=True, color="64748B")
GBP = '"£"#,##0;[Red]-"£"#,##0'
GBP2 = '"£"#,##0.00;[Red]-"£"#,##0.00'
ACTIVITIES = ["Drafting", "Meetings", "Court and hearings", "Research", "Calls and email", "Admin", "Business development"]
NON_BILLABLE = {"Admin", "Business development"}
MONTHS_FY = ["Apr-26", "May-26", "Jun-26", "Jul-26", "Aug-26", "Sep-26"]


def month_starts(first: date, n: int) -> list[date]:
    out, y, m = [], first.year, first.month
    for _ in range(n):
        out.append(date(y, m, 1))
        m += 1
        if m == 13:
            y, m = y + 1, 1
    return out


def rand_day(r: random.Random, month: date) -> date:
    return month + timedelta(days=r.randint(0, 27))


def write_table(ws, columns, rows, start_row=1, formats=None, widths=None):
    """A styled table: navy header, frozen header row, number formats and column widths."""
    formats = formats or {}
    for j, name in enumerate(columns, 1):
        c = ws.cell(row=start_row, column=j, value=name)
        c.fill, c.font = HEAD_FILL, HEAD_FONT
        c.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
    for i, row in enumerate(rows, start_row + 1):
        for j, v in enumerate(row, 1):
            c = ws.cell(row=i, column=j, value=v)
            fmt = formats.get(columns[j - 1])
            if fmt:
                c.number_format = fmt
            elif isinstance(v, date):
                c.number_format = "dd/mm/yyyy"
    ws.freeze_panes = ws.cell(row=start_row + 1, column=1)
    for j, name in enumerate(columns, 1):
        width = (widths or {}).get(name) or max(12, min(34, len(str(name)) + 4))
        ws.column_dimensions[get_column_letter(j)].width = width


def title_block(ws, title, subtitle):
    ws["A1"] = title
    ws["A1"].font = TITLE_FONT
    ws["A2"] = subtitle
    ws["A2"].font = NOTE_FONT
    return 4  # the table starts after a blank row


def readme_tab(wb, title, lines):
    ws = wb.active
    ws.title = "Read me"
    ws["A1"] = title
    ws["A1"].font = TITLE_FONT
    for i, line in enumerate(lines, 3):
        ws.cell(row=i, column=1, value=line)
    ws["A{}".format(len(lines) + 4)] = "Fictional sample data generated by meldra for demonstrations. Any resemblance to real organisations or people is coincidental."
    ws["A{}".format(len(lines) + 4)].font = NOTE_FONT
    ws.column_dimensions["A"].width = 120


def statement(wb, name, title, subtitle, items, periods, fmt=GBP):
    """Items down the side, periods across the top (P&L layout), under a title block."""
    ws = wb.create_sheet(name)
    start = title_block(ws, title, subtitle)
    cols = ["Line item", *periods]
    write_table(ws, cols, [[k, *v] for k, v in items], start_row=start, formats={p: fmt for p in periods}, widths={"Line item": 32})
    for i, (k, _) in enumerate(items, start + 1):
        if k in {"Gross profit", "EBITDA", "Net profit", "Operating profit", "Total income", "Total costs", "Surplus"}:
            for j in range(1, len(cols) + 1):
                ws.cell(row=i, column=j).font = Font(bold=True)
    return ws


def frame(columns, rows):
    return pd.DataFrame(rows, columns=columns)


def gbp(n):
    return round(float(n), 2)


