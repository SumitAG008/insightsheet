def manufacturing():
    r = random.Random(505)
    lines = {"Line A": 1.0, "Line B": 0.92, "Line C": 1.08, "Line D": 0.75}
    products = ["Valve body", "Pump housing", "Bracket", "Gear blank"]
    days = [date(2026, 7, 1) + timedelta(days=i) for i in range(92) if (date(2026, 7, 1) + timedelta(days=i)).weekday() < 5]
    prod = []
    for d in days:
        for line, eff in lines.items():
            for shift in ("Early", "Late"):
                planned = 480
                down = int(abs(r.gauss(28 if line != "Line D" else 64, 18)))
                units = int((planned - down) / 0.9 * eff * r.uniform(0.95, 1.03))
                scrap_rate = (0.018 if line != "Line C" else 0.041) * r.uniform(0.6, 1.4)
                prod.append([d, line, shift, r.choice(products), units, int(units * scrap_rate), down])
    prod_cols = ["Date", "Line", "Shift", "Product", "Units produced", "Units scrapped", "Downtime minutes"]

    inv = []
    cats = {"Raw material": 12, "Component": 18, "Consumable": 8, "Finished good": 10}
    k = 0
    for cat, n in cats.items():
        for _ in range(n):
            k += 1
            on_hand = r.randint(0, 2400)
            reorder = r.randint(150, 900)
            inv.append([f"SKU-{3000 + k}", f"{cat} {k:02d}", cat, on_hand, reorder, gbp(r.uniform(0.4, 85)),
                        "Reorder now" if on_hand < reorder else "OK"])
    inv_cols = ["SKU", "Description", "Category", "On hand", "Reorder point", "Unit cost", "Stock status"]

    oee_months = ["Jul-26", "Aug-26", "Sep-26"]
    oee = [(line, [round(r.uniform(0.68, 0.84) * (0.88 if line == "Line D" else 1) * 100, 1) for _ in oee_months]) for line in lines]

    wb = Workbook()
    readme_tab(wb, "Corran Precision Ltd: plant data, July to September 2026", [
        "Production: units, scrap and downtime per line and shift for every working day.",
        "Inventory: stock on hand against reorder points.",
        "OEE: overall equipment effectiveness by line and month, in %.",
        "Line C scraps the most; Line D loses the most time to downtime.",
    ])
    ws = wb.create_sheet("Production")
    write_table(ws, prod_cols, prod, formats={"Units produced": "#,##0", "Units scrapped": "#,##0"})
    ws = wb.create_sheet("Inventory")
    write_table(ws, inv_cols, inv, formats={"Unit cost": GBP2})
    statement(wb, "OEE", "Corran Precision Ltd: OEE by line", "Monthly, %.", oee, oee_months, fmt="0.0")
    wb.save(OUT / "manufacturing-corran-precision.xlsx")

    pr = frame(prod_cols, prod)
    g = pr.groupby("Line")
    return {
        "production_rows": len(pr),
        "units_by_line": {k: int(v) for k, v in g["Units produced"].sum().items()},
        "scrap_rate_by_line": {k: round(x["Units scrapped"].sum() / x["Units produced"].sum() * 100, 2) for k, x in g},
        "downtime_by_line": {k: int(v) for k, v in g["Downtime minutes"].sum().items()},
        "skus_to_reorder": sum(1 for row in inv if row[6] == "Reorder now"),
    }


