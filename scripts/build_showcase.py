# 2. Finance: multi-entity group, P&L, budget vs actual, revenue by customer
# ---------------------------------------------------------------------------------------------
def finance():
    r = random.Random(202)
    months = month_starts(date(2025, 10, 1), 12)
    labels = [m.strftime("%b-%y") for m in months]
    season = [0.92, 0.95, 1.08, 0.86, 0.9, 1.02, 0.98, 1.0, 1.04, 1.06, 0.97, 1.12]
    rev = [gbp(1_850_000 * s * (1 + i * 0.012) * r.uniform(0.98, 1.02)) for i, s in enumerate(season)]
    cogs = [gbp(x * r.uniform(0.54, 0.57)) for x in rev]
    gp = [gbp(a - b) for a, b in zip(rev, cogs)]
    staff = [gbp(r.uniform(318000, 334000) * (1 + i * 0.004)) for i in range(12)]
    prem = [gbp(r.uniform(88000, 92000)) for _ in range(12)]
    mkt = [gbp(r.uniform(42000, 76000)) for _ in range(12)]
    other = [gbp(r.uniform(51000, 63000)) for _ in range(12)]
    ebitda = [gbp(g - sum(x)) for g, *x in zip(gp, staff, prem, mkt, other)]
    pl = [("Revenue", rev), ("Cost of sales", cogs), ("Gross profit", gp), ("Staff costs", staff), ("Premises", prem),
          ("Marketing", mkt), ("Other overheads", other), ("EBITDA", ebitda)]

    depts = {"Sales": 61000, "Marketing": 52000, "Operations": 88000, "Technology": 74000, "Finance": 38000, "People": 29000}
    bva = []
    for m, lab in zip(months, labels):
        for d, base in depts.items():
            budget = gbp(base * (1 + 0.01 * months.index(m)))
            drift = 1.14 if d == "Technology" and m.month in (3, 4, 5, 6) else 1.0
            actual = gbp(budget * r.uniform(0.9, 1.08) * drift)
            bva.append([m, d, budget, actual, gbp(actual - budget)])
    bva_cols = ["Month", "Department", "Budget", "Actual", "Variance"]

    customers = {"Aldermoor Health": ("UK & Ireland", 1.4), "Brennan Mills": ("UK & Ireland", 0.9), "Castellan Bank": ("Europe", 1.6),
                 "Dovetail Retail": ("UK & Ireland", 1.1), "Everly Telecom": ("Europe", 1.3), "Fairhaven Council": ("UK & Ireland", 0.6),
                 "Greystone Energy": ("North America", 1.5), "Holloway Insurance": ("Europe", 0.8), "Ivory Coast Shipping": ("North America", 0.7),
                 "Juniper Education": ("UK & Ireland", 0.5)}
    lines = ["Software", "Support", "Services"]
    sales = []
    n = 0
    for m in months:
        for cust, (region, size) in customers.items():
            for line in lines:
                if r.random() < 0.55:
                    n += 1
                    amount = gbp(r.uniform(6000, 32000) * size * {"Software": 1.4, "Support": 0.6, "Services": 1.0}[line])
                    sales.append([f"INV-{50000 + n}", rand_day(r, m), cust, region, line, amount])
    sales_cols = ["Invoice", "Invoice date", "Customer", "Region", "Product line", "Amount"]

    wb = Workbook()
    readme_tab(wb, "Northbridge Group plc: finance pack, October 2025 to September 2026", [
        "Group P&L: twelve months of revenue, costs and EBITDA in statement layout (line items down, months across).",
        "Budget vs actual: monthly spend by department, with a deliberate overspend in Technology from March to June.",
        "Key account invoices: every invoice to the ten key accounts (about 15% of revenue), by region and product line.",
        "The intercompany case is in complex/intercompany-uk.xlsx and complex/intercompany-de.xlsx.",
    ])
    statement(wb, "Group P&L", "Northbridge Group plc: consolidated P&L", "Monthly, £. Management accounts, unaudited.", pl, labels)
    ws = wb.create_sheet("Budget vs actual")
    write_table(ws, bva_cols, bva, formats={"Budget": GBP, "Actual": GBP, "Variance": GBP})
    ws = wb.create_sheet("Key account invoices")
    write_table(ws, sales_cols, sales, formats={"Amount": GBP2}, widths={"Customer": 24, "Region": 18})
    wb.save(OUT / "finance-northbridge-group.xlsx")

    b = frame(bva_cols, bva)
    s = frame(sales_cols, sales)
    return {
        "revenue_total": gbp(sum(rev)),
        "ebitda_total": gbp(sum(ebitda)),
        "ebitda_margin": round(sum(ebitda) / sum(rev) * 100, 1),
        "budget_by_department": {k: gbp(v) for k, v in b.groupby("Department")["Budget"].sum().items()},
        "variance_by_department": {k: gbp(v) for k, v in b.groupby("Department")["Variance"].sum().items()},
        "sales_by_region": {k: gbp(v) for k, v in s.groupby("Region")["Amount"].sum().items()},
        "sales_invoices_rows": len(s),
    }


