def bank_vs_ledger():
    """Bank statement vs cash book: matches, timing differences, typos, rounding, duplicates."""
    r = random.Random(808)
    ledger, bank = [], []
    for i in range(1, 181):
        ref = f"PAY-{26000 + i}"
        amount = round(r.uniform(85, 18500), 2)
        d = date(2026, 9, 1) + timedelta(days=r.randint(0, 29))
        ledger.append([d, ref, f"Supplier {r.randint(1, 45):02d}", amount])
        bank.append([d + timedelta(days=r.randint(0, 2)), ref, amount])
    cases = {}
    # 1. Payments in the cash book that have not cleared the bank yet (timing differences).
    cleared_late = [b[1] for b in bank[-6:]]
    bank = bank[:-6]
    cases["in_ledger_not_bank"] = cleared_late
    # 2. Bank charges and interest the cash book has not recorded.
    extras = [[date(2026, 9, 30), "BANK-CHG-0926", 42.5], [date(2026, 9, 30), "INT-0926", -18.73], [date(2026, 9, 15), "DD-INSURE-09", 1265.0]]
    bank += extras
    cases["in_bank_not_ledger"] = [e[1] for e in extras]
    # 3. Amounts keyed wrongly in the cash book's counterpart (90 out: a transposed-digit typo).
    for idx in (14, 77, 123):
        bank[idx][2] = round(bank[idx][2] + 90, 2)
    cases["amount_mismatch"] = [bank[i][1] for i in (14, 77, 123)]
    # 4. Penny rounding differences (cleared by a 0.01 tolerance).
    for idx in (30, 31):
        bank[idx][2] = round(bank[idx][2] + 0.01, 2)
    cases["rounding"] = [bank[i][1] for i in (30, 31)]
    # 5. A payment entered twice in the cash book.
    dup = list(ledger[60])
    ledger.append(dup)
    cases["duplicate_in_ledger"] = [dup[1]]
    # 6. References with stray spaces in the bank file (trimmed before matching).
    for idx in (5, 6, 7):
        bank[idx][1] = f" {bank[idx][1]} "

    wb = Workbook()
    ws = wb.active
    ws.title = "Cash book"
    write_table(ws, ["Date", "Reference", "Payee", "Amount"], ledger, formats={"Amount": GBP2})
    wb.save(OUT / "complex" / "cash-book-september.xlsx")
    pd.DataFrame(
        [[b[0].strftime("%d/%m/%Y"), b[1], f"{b[2]:.2f}" if b[2] >= 0 else f"({abs(b[2]):.2f})"] for b in bank],
        columns=["Transaction date", "Reference", "Amount"],
    ).to_csv(OUT / "complex" / "bank-statement-september.csv", index=False)
    return {"cash_book_rows": len(ledger), "bank_rows": len(bank), "planted": cases}


