def insurance():
    r = random.Random(404)
    lobs = {"Motor": (5200, 0.62), "Property": (14800, 0.55), "Liability": (22500, 0.48), "Marine": (31000, 0.71)}
    regions = ["London", "South East", "Midlands", "North", "Scotland"]
    causes = {"Motor": ["Collision", "Theft", "Windscreen"], "Property": ["Escape of water", "Fire", "Storm", "Theft"],
              "Liability": ["Slip or trip", "Product fault", "Professional error"], "Marine": ["Cargo damage", "Hull damage", "Delay"]}
    months = month_starts(date(2025, 10, 1), 12)
    claims = []
    for i in range(1, 641):
        lob = r.choices(list(lobs), weights=[45, 30, 17, 8])[0]
        sev, _ = lobs[lob]
        loss = rand_day(r, r.choice(months))
        notified = loss + timedelta(days=int(abs(r.gauss(9, 8))))
        incurred = gbp(abs(r.lognormvariate(0, 0.9)) * sev)
        status = r.choices(["Closed", "Open", "Reopened"], weights=[58, 37, 5])[0]
        paid = incurred if status == "Closed" else gbp(incurred * r.uniform(0, 0.6))
        claims.append([f"CLM-{70000 + i}", f"POL-{r.randint(100000, 199999)}", lob, r.choice(regions), r.choice(causes[lob]),
                       loss, notified, status, paid, gbp(incurred - paid), incurred])
    claim_cols = ["Claim ID", "Policy ID", "Line of business", "Region", "Cause", "Loss date", "Notified date", "Status", "Paid", "Reserve", "Incurred"]
    # Incurred is the measure people chart, so it is the first number column: move it before Paid.
    order = [0, 1, 2, 3, 4, 5, 6, 7, 10, 8, 9]
    claim_cols = [claim_cols[i] for i in order]
    claims = [[row[i] for i in order] for row in claims]

    cl = frame(claim_cols, claims)
    prem = []
    for m in months:
        for lob in lobs:
            inc = cl[(pd.to_datetime(cl["Loss date"]).dt.month == m.month) & (cl["Line of business"] == lob)]["Incurred"].sum()
            earned = gbp(inc / lobs[lob][1] * r.uniform(0.94, 1.06)) if inc else gbp(r.uniform(40000, 90000))
            prem.append([m, lob, gbp(earned * r.uniform(1.0, 1.12)), earned])
    prem_cols = ["Month", "Line of business", "Written premium", "Earned premium"]

    wb = Workbook()
    readme_tab(wb, "Kingsmere Underwriting: claims bordereau, October 2025 to September 2026", [
        "Claims: one row per claim with paid, reserve and incurred.",
        "Premiums: written and earned premium by month and line of business.",
        "Loss ratio = incurred claims / earned premium. Marine runs hottest on purpose.",
    ])
    ws = wb.create_sheet("Claims")
    write_table(ws, claim_cols, claims, formats={k: GBP2 for k in ["Paid", "Reserve", "Incurred"]}, widths={"Cause": 18, "Line of business": 16})
    ws = wb.create_sheet("Premiums")
    write_table(ws, prem_cols, prem, formats={"Written premium": GBP, "Earned premium": GBP})
    wb.save(OUT / "insurance-kingsmere-claims.xlsx")

    p = frame(prem_cols, prem)
    lr = {lob: round(cl[cl["Line of business"] == lob]["Incurred"].sum() / p[p["Line of business"] == lob]["Earned premium"].sum() * 100, 1) for lob in lobs}
    return {
        "claims_rows": len(cl),
        "incurred_by_line": {k: gbp(v) for k, v in cl.groupby("Line of business")["Incurred"].sum().items()},
        "loss_ratio_by_line": lr,
        "open_reserve_total": gbp(cl[cl["Status"] != "Closed"]["Reserve"].sum()),
    }


