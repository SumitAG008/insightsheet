export const LEGAL_STRINGS = { en, hi };
export const LEGAL_LANGUAGES = [
  { code: 'en', label: 'English' },
  { code: 'hi', label: 'हिन्दी' },
];

// t('likely_adjourned', { p: 70 }) → "Adjourned in 70% of similar hearings". Missing Hindi falls back to English.
export function translate(lang, key, vars) {
  const table = LEGAL_STRINGS[lang] || en;
  let s = table[key] ?? en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  }
  return s;
}

// First visit: Hindi when the phone or browser is set to Hindi and the firm is in India; otherwise English.
export function defaultLanguage(country, navigatorLanguages = []) {
  const langs = (navigatorLanguages || []).map((l) => String(l).toLowerCase());
  return country === 'IN' && langs.some((l) => l.startsWith('hi')) ? 'hi' : 'en';
}
